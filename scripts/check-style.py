#!/usr/bin/env python3
"""Check mechanical rules; semantic style rules still require code review."""
from pathlib import Path
import sys
import re

maximum_length = 90
extensions = {'.cs', '.ts', '.js', '.mjs', '.svelte', '.py', '.sh', '.proto'}
excluded = {
    'obj', 'bin', 'Migrations', 'node_modules', '.svelte-kit', 'generated', 'wwwroot'
}
failures = []

for root in ('src', 'tests', 'scripts'):
    for path in Path(root).rglob('*'):
        if not path.is_file() or path.suffix not in extensions:
            continue

        if excluded.intersection(path.parts):
            continue

        content = path.read_text()
        lines = content.splitlines()
        generated = path.name.endswith(('.g.cs', '.generated.cs', '.Designer.cs'))
        generated = generated or '<auto-generated' in '\n'.join(lines[:8]).lower()

        if generated:
            continue

        if path.suffix == '.cs':
            namespace = re.search(r'^namespace ([\w.]+)[;{]', content, re.MULTILINE)
            expected = '.'.join(path.parts[1:-1])

            if namespace is None or namespace.group(1) != expected:
                failures.append(f'{path}: namespace must be {expected}')


        for index, line in enumerate(lines):
            context = line + (lines[index - 1] if index else '')
            message = re.search(
                r'(?:\w*(?:Exception|Error)|Log\w*|console\.\w+|print)\s*\(',
                context)
            literal = r"(?:\$?\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'|`[^`]*`)"
            shortened = re.sub(literal, '""', line)
            long_message = message and len(shortened) <= maximum_length

            if len(line) > maximum_length and not long_message:
                failures.append(f'{path}:{index + 1}: exceeds {maximum_length} chars')

            if line.strip().startswith('}') and index and not lines[index - 1].strip():
                failures.append(f'{path}:{index + 1}: blank line at block end')

for failure in failures:
    print(failure)

sys.exit(bool(failures))
